print("// This is made by lib/convert-unicode-database.py from Modules/%s of CPython %s.%s, which is made from version %s of the Unicode Character Database." % ({"data": "unicodedata_db.h", "names": "unicodename_db.h"}[which], python[0], python[1], version))
print("// It is not to be changed by hand.\n")
