text = source
# What made it, which is said again below
text = re.sub(r"\A/\* this file was generated by .*? \*/\n+", "", text)
text = re.sub(r'#define UNIDATA_VERSION ".*?"\n', "", text)
text = re.sub(r"#define (\w+) (\d+)\n", lambda m: "static constexpr unsigned %s = %s;\n" % m.groups(), text)
text = text.replace("struct reindex{int start;short count,index;};", "struct reindex {\n    int start;\n    short count;\n    short index;\n};")
text = text.replace("static struct reindex ", "static const reindex ")
text = re.sub(r"typedef struct NamedSequence \{(.*?)\} named_sequence;", r"struct named_sequence {\1};", text, flags=re.S)
text = re.sub(r"typedef struct \{(.*?)\} derived_name_range;", r"struct derived_name_range {\1};", text, flags=re.S)


def literals(match):
    "An array of strings of C's, which may end with NULL, as an array of ASCIILiteral"
    body = re.sub(r"\n\s*NULL,?", "", match.group(2))
    return "static constexpr ASCIILiteral %s[] = {%s};" % (match.group(1), re.sub(r'("[^"]*")', r"\1_s", body))


text = re.sub(r"(?:static )?const char \*\s*(?:const )?(\w+)\[\] = \{(.*?)\};", literals, text, flags=re.S)
text = re.sub(r"^const (\w+ \w+\[\] = \{)", r"static const \1", text, flags=re.M)
text = re.sub(r"^static const (?=[\w ]+\[\] = \{|unsigned int \w+ = )", "static constexpr ", text, flags=re.M)
text = text.replace("static const change_record* get_change_3_2_0(", "inline const change_record* get_change_3_2_0(").replace("static Py_UCS4 normalization_3_2_0(", "inline Py_UCS4 normalization_3_2_0(")
text = text.replace("    if (n >= 0x110000) index = 0;\n", "    if (n >= 0x110000)\n        index = 0;\n").replace("switch(n)", "switch (n)").replace("[n>>8]", "[n >> 8]").replace("[(index<<8)+(n & 255)]", "[(index << 8) + (n & 255)]").replace("change_records_3_2_0+index", "change_records_3_2_0 + index")
text = re.sub(r"\b(%s)\b" % "|".join(sorted(NAMES, key=len, reverse=True)), lambda m: NAMES[m.group(1)], text)
text = re.sub(r"[ \t]+$", "", text, flags=re.M).strip("\n")

