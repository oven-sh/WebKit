# Makes PythonUnicodeDatabase.h out of Modules/unicodedata_db.h of CPython, and PythonUnicodeNames.h out of Modules/unicodename_db.h.
#
#     python3 convert-unicode-database.py <the directory that CPython's source is in> data > ../PythonUnicodeDatabase.h
#     python3 convert-unicode-database.py <the directory that CPython's source is in> names > ../PythonUnicodeNames.h
#
# The numbers are left as they are. What is changed is what C++ and this directory call things.
import re
import sys

directory, which = sys.argv[1:]
source = open(directory + {"data": "/Modules/unicodedata_db.h", "names": "/Modules/unicodename_db.h"}[which]).read()
version = re.search(r'#define UNIDATA_VERSION "(.*?)"', open(directory + "/Modules/unicodedata_db.h").read()).group(1)
python = re.search(r'#define PY_MAJOR_VERSION\s+(\d+)\n#define PY_MINOR_VERSION\s+(\d+)', open(directory + "/Include/patchlevel.h").read()).groups()

