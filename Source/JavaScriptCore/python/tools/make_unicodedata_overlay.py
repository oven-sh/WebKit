"""Writes runtime/PyUnicodeDataNew.h and parser/PyUnicodeNewNames.h: what the module unicodedata has to say about the
characters of which ICU, being of an older version of Unicode than the Python we implement, says something else.

    bun make_unicodedata_overlay.py dump FILE        what unicodedata says with ICU alone
    python3 make_unicodedata_overlay.py make FILE PYTHON_DIRECTORY

The first is to be run by a build whose two headers are empty (make /dev/null PYTHON_DIRECTORY writes such), the second by a
CPython with the version of Unicode that is wanted; PYTHON_DIRECTORY is Source/JavaScriptCore/python.

The values are those of the version wanted, not differences, so an ICU that has caught up changes nothing. One that is ahead
does: then this is the wrong tool.
"""

import sys
import unicodedata

LIMIT = 0x110000
PROPERTIES = ["category", "bidirectional", "combining", "east_asian_width", "mirrored", "decomposition", "grapheme_cluster_break",
              "extended_pictographic"]
WITH_DEFAULT = ["decimal", "digit", "numeric", "name"]

# In the order of ICU's enumerations.
CATEGORIES = "Cn Lu Ll Lt Lm Lo Mn Me Mc Nd Nl No Zs Zl Zp Cc Cf Co Cs Pd Ps Pe Pc Po Sm Sc Sk So Pi Pf".split()
DIRECTIONS = "L R EN ES ET AN CS B S WS ON LRE LRO AL RLE RLO PDF NSM BN FSI LRI RLI PDI".split()
WIDTHS = "N A H F Na W".split()
BREAKS = "Other Control CR Extend L LF LV LVT T V SpacingMark Prepend Regional_Indicator - - - - ZWJ".split()
TAGS = "- - <compat> <circle> <final> <font> <fraction> <initial> <isolated> <medial> <narrow> <noBreak> <small> <square> <sub> <super> <vertical> <wide>".split()


def row(code):
    character = chr(code)
    return ([getattr(unicodedata, name)(character) for name in PROPERTIES]
            + [getattr(unicodedata, name)(character, None) for name in WITH_DEFAULT])


def dump(path):
    with open(path, "w") as file:
        for code in range(LIMIT):
            file.write(repr(row(code)) + "\n")


def ranges(values):
    """{code: value} as [(first, last, value)]."""
    result = []
    for code in sorted(values):
        if result and result[-1][1] == code - 1 and result[-1][2] == values[code]:
            result[-1][1] = code
        else:
            result.append([code, code, values[code]])
    return result


def table(out, comment, kind, name, values, show=str):
    out.append("// %s" % comment)
    out.append("static constexpr %s %s[] = {" % (kind, name))
    for first, last, value in ranges(values):
        out.append("    { 0x%04X, 0x%04X, %s }," % (first, last, show(value)))
    if not values:
        out.append("    { 1, 0, 0 },")
    out.append("};")
    out.append("")


HEADER = """/*
 * Copyright (C) 2026 Oven, Inc. All rights reserved.
 * SPDX-License-Identifier: BSD-2-Clause
 */

#pragma once

// Generated by tools/make_unicodedata_overlay.py; do not edit.
//
"""


def make(path, directory):
    import ast
    with open(path) as file:
        theirs = [ast.literal_eval(line) for line in file]
    names = PROPERTIES + WITH_DEFAULT
    different = {name: {} for name in names}
    for code in range(LIMIT if theirs else 0):
        for name, wanted, found in zip(names, row(code), theirs[code]):
            if wanted != found:
                different[name][code] = wanted

    version = unicodedata.unidata_version
    out = [HEADER + "// What the properties of characters are in Unicode %s where the ICU this was made with says otherwise. For PyUnicodeData.cpp."
           % version, "", "namespace JSC {", "namespace Python {", "",
           'static constexpr ASCIILiteral unicodeNewVersion = "%s"_s;' % version,
           "static constexpr unsigned unicodeNewMajorVersion = %s;" % version.split(".")[0], "",
           "struct UnicodeNewValue {", "    char32_t first;", "    char32_t last;", "    int value;", "};", "",
           "struct UnicodeNewNumber {", "    char32_t first;", "    char32_t last;", "    double value;", "};", ""]
    table(out, "A UCharCategory.", "UnicodeNewValue", "unicodeNewCategories", {c: CATEGORIES.index(v) for c, v in different["category"].items()})
    table(out, "A UCharDirection. -1: none, as the character is not assigned.", "UnicodeNewValue", "unicodeNewDirections",
          {c: DIRECTIONS.index(v) if v else -1 for c, v in different["bidirectional"].items()})
    table(out, "The canonical combining class.", "UnicodeNewValue", "unicodeNewCombiningClasses", different["combining"])
    table(out, "A UEastAsianWidth.", "UnicodeNewValue", "unicodeNewWidths", {c: WIDTHS.index(v) for c, v in different["east_asian_width"].items()})
    table(out, "Bidi_Mirrored.", "UnicodeNewValue", "unicodeNewMirrored", different["mirrored"])
    table(out, "A UGraphemeClusterBreak.", "UnicodeNewValue", "unicodeNewGraphemeBreaks",
          {c: BREAKS.index(v) for c, v in different["grapheme_cluster_break"].items()})
    table(out, "Extended_Pictographic.", "UnicodeNewValue", "unicodeNewPictographic", {c: int(v) for c, v in different["extended_pictographic"].items()})
    table(out, "-1: none.", "UnicodeNewValue", "unicodeNewDecimals", {c: -1 if v is None else v for c, v in different["decimal"].items()})
    table(out, "-1: none.", "UnicodeNewValue", "unicodeNewDigits", {c: -1 if v is None else v for c, v in different["digit"].items()})
    table(out, "-1: none.", "UnicodeNewNumber", "unicodeNewNumerics", {c: -1.0 if v is None else v for c, v in different["numeric"].items()}, repr)

    out += ["// Decomposition_Mapping, not applied again to its own result. `type` is a UDecompositionType. `composes`: the two characters of a",
            "// canonical mapping are put together again by NFC.",
            "struct UnicodeNewDecomposition {", "    char32_t character;", "    uint8_t type;", "    bool composes;", "    uint8_t length;",
            "    char32_t parts[4];", "};", "", "// In order.", "static constexpr UnicodeNewDecomposition unicodeNewDecompositions[] = {"]
    for code, text in sorted(different["decomposition"].items()):
        fields = text.split()
        kind = 1 if fields else 0
        if fields and fields[0].startswith("<"):
            kind = TAGS.index(fields.pop(0))
        parts = [int(field, 16) for field in fields]
        assert len(parts) <= 4, (hex(code), text)
        composes = kind == 1 and len(parts) == 2 and unicodedata.normalize("NFC", "".join(map(chr, parts))) == chr(code)
        out.append("    { 0x%04X, %d, %s, %d, { %s } }," % (code, kind, "true" if composes else "false", len(parts), ", ".join("0x%04X" % p for p in parts) or "0"))
    if not different["decomposition"]:
        out.append("    { 0, 0, false, 0, { 0 } },")
    out += ["};", "", "} // namespace Python", "} // namespace JSC", ""]
    with open(directory + "/runtime/PyUnicodeDataNew.h", "w") as file:
        file.write("\n".join(out))

    # Names. Those that end with the number of the character need no table.
    computed, listed = {}, {}
    for code, name in different["name"].items():
        assert name is not None, hex(code)
        prefix, _, digits = name.rpartition("-")
        if digits == "%04X" % code:
            computed[code] = prefix + "-"
        else:
            listed[code] = name
    out = [HEADER + "// The names of the characters of Unicode %s that the ICU this was made with does not know. For PyUnicode.cpp." % version, "",
           "namespace JSC {", "namespace Python {", "",
           "// The name is the prefix and the number of the character, in hexadecimal.",
           "struct UnicodeNewNameRange {", "    char32_t first;", "    char32_t last;", "    ASCIILiteral prefix;", "};", "",
           "static constexpr UnicodeNewNameRange unicodeNewNameRanges[] = {"]
    for first, last, prefix in ranges(computed):
        out.append('    { 0x%04X, 0x%04X, "%s"_s },' % (first, last, prefix))
    if not computed:
        out.append('    { 1, 0, ""_s },')
    out += ["};", "", "struct UnicodeNewName {", "    char32_t character;", "    ASCIILiteral name;", "};", "", "// In the order of the characters.",
            "static constexpr UnicodeNewName unicodeNewNames[] = {"]
    codes = sorted(listed)
    for code in codes:
        out.append('    { 0x%04X, "%s"_s },' % (code, listed[code]))
    if not codes:
        out.append('    { 0, ""_s },')
    out += ["};", "", "// Indices into that table, in the order of the names.", "static constexpr uint16_t unicodeNewNamesByName[] = {"]
    order = sorted(range(len(codes)), key=lambda i: listed[codes[i]])
    for start in range(0, len(order), 24):
        out.append("    " + " ".join("%d," % i for i in order[start:start + 24]))
    if not codes:
        out.append("    0,")
    out += ["};", "", "} // namespace Python", "} // namespace JSC", ""]
    with open(directory + "/parser/PyUnicodeNewNames.h", "w") as file:
        file.write("\n".join(out))
    print({name: len(values) for name, values in different.items()}, "names listed:", len(listed), "computed:", len(computed))


if __name__ == "__main__":
    if len(sys.argv) == 3 and sys.argv[1] == "dump":
        dump(sys.argv[2])
    elif len(sys.argv) == 4 and sys.argv[1] == "make":
        make(sys.argv[2], sys.argv[3])
    else:
        sys.exit(__doc__)
