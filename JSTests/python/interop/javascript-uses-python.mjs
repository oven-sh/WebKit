import m from "./shapes.py";
function show(label, f) { try { print(label, "=>", f()); } catch (e) { print(label, "!! threw", String(e), "| instanceof Error:", e instanceof Error); } }
show("typeof module", () => typeof m);
show("call add(1)", () => m.add(1));
show("call add(1, 2)", () => m.add(1, 2));
show("new-less construct", () => { const p = m.Point(3, 4); return [typeof p, p.x, p.y, p.norm2()].join(" "); });
show("instanceof", () => m.Point(1, 2) instanceof m.Point);
show("set attr from JS", () => { const p = m.Point(3, 4); p.x = 10; return p.norm2(); });
show("Object.keys(instance)", () => Object.keys(m.Point(3, 4)).join());
show("JSON.stringify(instance)", () => JSON.stringify(m.Point(3, 4)));
show("list is Array", () => [Array.isArray(m.numbers), m.numbers.length, m.numbers.map(x => x * 2).join()].join(" "));
show("push seen by python", () => { m.numbers.push(4); return m.describe(m.numbers); });
show("for-of generator", () => { const out = []; for (const v of m.squares(4)) out.push(v); return out.join(); });
show("spread generator", () => [...m.squares(3)].join());
show("bytes is Uint8Array", () => [m.data instanceof Uint8Array, m.data.length, m.data[0]].join(" "));
show("describe(1)", () => m.describe(1));
show("describe(1.5)", () => m.describe(1.5));
show("describe('s')", () => m.describe("s"));
show("describe(null)", () => m.describe(null));
show("describe(undefined)", () => m.describe(undefined));
show("describe(true)", () => m.describe(true));
show("describe([1,'a'])", () => m.describe([1, "a"]));
show("describe({a:1})", () => m.describe({ a: 1 }));
show("describe(x=>x)", () => m.describe(x => x));
show("describe(10n**30n)", () => m.describe(10n ** 30n));
show("describe(new Uint8Array(2))", () => m.describe(new Uint8Array(2)));
show("describe(new Map)", () => m.describe(new Map([[1, 2]])));
show("python calls JS fn", () => m.call_it((a, b) => a + b, 2, 3));
show("python exception in JS", () => m.boom());
show("JS exception through python", () => m.call_it(() => { throw new RangeError("from js"); }));
show("dict from JS", () => [typeof m.table, m.table.a, m.describe(m.table)].join(" "));
show("String(instance)", () => String(m.Point(1, 2)));
